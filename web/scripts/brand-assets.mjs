// Builds the wordmark and icon outputs from the outlined SVG sources in public/brand/ (D6: direction C,
// Two Voices, with favicon C2, The Noted R; Matt, Nov 1, 2026). Run from web/: node scripts/brand-assets.mjs
// Writes components/icons/wordmark-paths.ts, app/icon.svg, app/favicon.ico, app/apple-icon.png, and the
// manifest PNGs in public/brand/. The sources come from docs/design-explorations/wordmark-2026-11/.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const brand = (file) => path.join(ROOT, "public", "brand", file);
const read = (file) => fs.readFileSync(brand(file), "utf8");
const INK = "#111513";

function parseLogotype(file) {
  const svg = read(file);
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const lines = [...svg.matchAll(/<g transform="translate\(([-\d.]+) ([-\d.]+)\)">([\s\S]*?)<\/g>/g)].map((group) => ({
    x: Number(group[1]),
    y: Number(group[2]),
    paths: [...group[3].matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)].map((p) => ({ d: p[1], voice: p[2].toLowerCase() === INK ? "ink" : "pen" })),
  }));
  if (!lines.length || !lines.some((line) => line.paths.some((p) => p.voice === "pen"))) throw new Error(`${file}: expected ink and pen paths`);
  return { viewBox, lines };
}

function writePaths() {
  const out = { line: parseLogotype("logotype.svg"), stacked: parseLogotype("logotype-stacked.svg") };
  const body = `// Generated by scripts/brand-assets.mjs from public/brand/logotype*.svg. Do not edit by hand.
// Outlines of Schibsted Grotesk ExtraBold ("ink") and Literata Italic ("pen": the word "in").
export const WORDMARK = ${JSON.stringify(out, null, 2)} as const;
`;
  fs.writeFileSync(path.join(ROOT, "components", "icons", "wordmark-paths.ts"), body);
}

/** One favicon that follows the browser theme: paper tile by default, ink tile in dark mode. */
function writeAdaptiveIcon() {
  const fills = (svg) => [...svg.matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)].map((m) => ({ d: m[1], fill: m[2] }));
  const light = fills(read("favicon-32-light.svg"));
  const dark = fills(read("favicon-32-dark.svg"));
  if (light.length !== 3 || dark.length !== 3) throw new Error("favicon sources must be tile, letter, stroke");
  const names = ["tile", "letter", "stroke"];
  const rules = (set) => names.map((name, i) => `.${name}{fill:${set[i].fill}}`).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><style>${rules(light)}@media (prefers-color-scheme:dark){${rules(dark)}}</style>${light.map((p, i) => `<path class="${names[i]}" d="${p.d}"/>`).join("")}</svg>\n`;
  fs.writeFileSync(path.join(ROOT, "app", "icon.svg"), svg);
}

async function png(file, size) {
  const svg = read(file);
  const viewSize = Number(svg.match(/viewBox="0 0 (\d+)/)[1]);
  return sharp(Buffer.from(svg), { density: (72 * size) / viewSize }).resize(size, size).png().toBuffer();
}

/** A PNG-in-ICO file: the 16px drawing (redrawn on whole pixels) and the 32px drawing, on the paper tile. */
async function writeIco() {
  const images = [
    { size: 16, data: await png("favicon-16-light.svg", 16) },
    { size: 32, data: await png("favicon-32-light.svg", 32) },
  ];
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach((image, index) => {
    const entry = 6 + index * 16;
    header.writeUInt8(image.size, entry);
    header.writeUInt8(image.size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(image.data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += image.data.length;
  });
  fs.writeFileSync(path.join(ROOT, "app", "favicon.ico"), Buffer.concat([header, ...images.map((image) => image.data)]));
}

async function writeAppIcons() {
  // Home screens get the ink tile, full bleed; iOS and Android round it themselves. The letter and stroke
  // sit inside the central 80% circle, so the same art is safe as a maskable icon.
  fs.writeFileSync(path.join(ROOT, "app", "apple-icon.png"), await png("favicon-180-dark.svg", 180));
  fs.writeFileSync(brand("icon-192.png"), await png("favicon-180-dark.svg", 192));
  fs.writeFileSync(brand("icon-512.png"), await png("favicon-180-dark.svg", 512));
}

writePaths();
writeAdaptiveIcon();
await writeIco();
await writeAppIcons();
console.log("brand assets written");
