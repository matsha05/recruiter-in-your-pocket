#!/usr/bin/env python3
"""Turns outputs/*.json into results.md (one row per run) and a few aggregate numbers. No model calls."""
import glob, json, os, re, sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "outputs")
RESULTS = os.path.join(HERE, "..", "results.md")
MARKS = json.load(open(os.path.join(HERE, "marks.json")))["cases"]

def load():
    runs = []
    for f in sorted(glob.glob(os.path.join(OUT, "*__run*.json"))):
        d = json.load(open(f))
        d["_file"] = os.path.basename(f)
        runs.append(d)
    return runs

def cell(s, n=None):
    s = "" if s is None else str(s)
    s = s.replace("|", "/").replace("\n", " ").strip()
    if n and len(s) > n:
        s = s[: n - 1] + "…"
    return s

def fixes_cell(p):
    parts = []
    for i, fx in enumerate(p.get("fixes", [])):
        tag = "CM" if fx.get("critical") is True else ("fix" if fx.get("critical") is False else "unflagged")
        parts.append(f"{i+1} [{tag}] {cell(fx.get('fix'))} ← \"{cell(fx.get('excerpt'))}\"")
    return "<br>".join(parts)

def mark_of(d):
    m = MARKS.get(d["case_id"], {})
    return cell(m.get("lead", "")), cell(m.get("runs", {}).get(str(d["run"]), m.get("default", "")))

def row(d):
    p = d.get("presentation")
    cost = f"${float(d.get('cost_usd') or 0):.4f}"
    lead, mark = mark_of(d)
    if not p:
        why = d.get("request_refusal", {}).get("message") or d.get("initial_validation_error", {}).get("message") or d.get("repair_error", {}).get("message") or d.get("provider_error", {}).get("message") or d.get("error", "")
        return f"| {d['case_id']} | {d['run']} | **{d['outcome']}** | | | {cell(why, 260)} | | | | {lead} | {mark} | {cost} |"
    sev = p.get("severity_outcome", "")
    added = ",".join(p.get("severity_added") or []) or "none"
    promoted = p.get("severity_promoted") or []
    sev_cell = f"{sev}; added {added}" + (f"; promoted {promoted}" if promoted else "")
    refusal = d.get("initial_validation_error", {}).get("message", "")
    refusal_cell = f"first draft refused ({cell(refusal, 160)}); repaired" if refusal else ""
    rw = p.get("first_rewrite")
    rw_cell = f"\"{cell(rw.get('original'))}\" → \"{cell(rw.get('better'))}\"" if rw else "none"
    return (
        f"| {d['case_id']} | {d['run']} | {p['band']} ({p['score']}) | {cell(p.get('verdict'))} | {fixes_cell(p)} | "
        f"{rw_cell} | {cell(p.get('keep'))} | {sev_cell} | {refusal_cell} | {lead} | {mark} | {cost} |"
    )

def main():
    runs = load()
    by_case = defaultdict(list)
    for d in runs:
        by_case[d["case_id"]].append(d)
    lines = ["# Results, one row per run", "",
             "Generated by `tools/summarize.py` from `outputs/*.json` and `tools/marks.json` (the recruiter lead per case, written blind in `recruiter-leads.md`, and the per-run mark).", "",
             "| Case | Run | Band (score) | Verdict | Fixes in page order (CM = flagged Critical Miss) with quoted excerpt | First rewrite | Keep this one | Severity check | Validator | A sharp recruiter would lead with | Did the report? | Cost |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for case in sorted(by_case):
        for d in sorted(by_case[case], key=lambda x: x["run"]):
            lines.append(row(d))
    # Aggregates
    reports = [d for d in runs if d.get("presentation")]
    total_cost = sum(float(d.get("cost_usd") or 0) for d in runs)
    bands = Counter(d["presentation"]["band"] for d in reports)
    scores = sorted(d["presentation"]["score"] for d in reports)
    cm_counts = Counter(d["presentation"]["critical_count"]["count"] for d in reports)
    added = Counter(k for d in reports for k in (d["presentation"].get("severity_added") or []))
    outcomes = Counter(d["outcome"] for d in runs)
    repaired = sum(1 for d in runs if d.get("repaired"))
    refused_first = sum(1 for d in runs if d.get("initial_validation_error"))
    rewrites = sum(1 for d in reports if d["presentation"].get("rewrites_count"))
    # Repeat stability: first-fix excerpt agreement within a case
    same_first, cases_with_repeats, cm_set_changes = 0, 0, 0
    detail = []
    for case, ds in by_case.items():
        ps = [d["presentation"] for d in ds if d.get("presentation")]
        if len(ps) < 2:
            continue
        cases_with_repeats += 1
        firsts = {re.sub(r"\W+", " ", (p["fixes"][0].get("excerpt") or "")).strip().lower() for p in ps if p.get("fixes")}
        if len(firsts) == 1:
            same_first += 1
        cm_sets = [tuple(re.sub(r"\W+", " ", (f.get("excerpt") or "")).strip().lower() for f in p["fixes"] if f.get("critical") is True) for p in ps]
        if len(set(cm_sets)) > 1:
            cm_set_changes += 1
        sc = [p["score"] for p in ps]
        detail.append(f"| {case} | {len(ps)} | {'same' if len(firsts)==1 else 'differs'} | {len(set(cm_sets))} | {min(sc)}-{max(sc)} | {sorted(set(p['band'] for p in ps))} |")
    lines += ["", "## Aggregates", "",
              f"- Runs: {len(runs)}; outcomes {dict(outcomes)}; shipped reports {len(reports)}",
              f"- Spend (token-priced): ${total_cost:.4f}",
              f"- Bands: {dict(bands)}; scores min {scores[0] if scores else None}, median {scores[len(scores)//2] if scores else None}, max {scores[-1] if scores else None}",
              f"- Critical Miss counts: {dict(cm_counts)}; severity additions by kind: {dict(added)}",
              f"- First draft refused by the validator: {refused_first}; repaired and shipped: {repaired}; reports with a model rewrite: {rewrites} of {len(reports)}",
              f"- Repeats: {cases_with_repeats} cases with 2+ shipped runs; first fix on the same line in {same_first}; Critical Miss set changed in {cm_set_changes}",
              "", "| Case | Shipped runs | First-fix line | Distinct CM sets | Score range | Bands |", "| --- | --- | --- | --- | --- | --- |", *detail]
    open(RESULTS, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[lines.index("## Aggregates"):]))

if __name__ == "__main__":
    main()
